/* ------------------------------------------------------------------ *
 * Build the flat card list
 * ------------------------------------------------------------------ */

const splitKeywords = (s) => s.split(",").map((k) => k.trim());

const CARDS = [];

MAJOR_DATA.forEach(([id, name, glyph, kw, up, rev], i) => {
  CARDS.push({
    id,
    arcana: "major",
    suit: null,
    number: i,
    label: ROMAN[i],
    name,
    glyph,
    keywords: splitKeywords(kw),
    upright: up,
    reversed: rev,
  });
});

SUIT_ORDER.forEach((suit) => {
  RANKS.forEach((rank, i) => {
    const [kw, up, rev] = MINOR_DATA[suit][i];
    CARDS.push({
      id: `${suit}-${rank.key}`,
      arcana: "minor",
      suit,
      rank: rank.key,
      number: i + 1,
      label: rank.label,
      name: `${rank.name} of ${SUITS[suit].name}`,
      keywords: splitKeywords(kw),
      upright: up,
      reversed: rev,
    });
  });
});

const CARD_BY_ID = new Map(CARDS.map((c) => [c.id, c]));

